<#
.SYNOPSIS
    把本库 always-apply 的 rules 与 skills 分发到 dsh 的 harness home。幂等，可反复跑。

.DESCRIPTION
    dsh 不读 .mdc：always-apply rule 去掉 frontmatter 后按文件名顺序拼成 $DshHome\AGENTS.md，
    这是生成文件，rule 改动后重跑。skills 由 scripts/install-skills.py 逐个链接到
    $DshHome\skills\<name>，含 ~/.agent-loop/packs.txt 登记的 skill 包；那里其他 skill 不动。
    hooks 与 provider 仍按 docs/usage.md 手工配置。
#>
param([string]$DshHome = $env:DSH_HOME)

$ErrorActionPreference = 'Stop'
if (-not $DshHome) { throw "dsh home not set: pass -DshHome <path> or set DSH_HOME (dsh defaults to ~/.dsh)" }
$repo = Split-Path $PSScriptRoot -Parent
$stamp = Get-Date -f yyyyMMdd-HHmmss
New-Item -ItemType Directory -Force $DshHome | Out-Null

# --- Rules：生成 AGENTS.md ---
$marker = '<!-- Generated by agent-loop scripts/sync-to-dsh.ps1 from rules/*.mdc; edits are overwritten on the next sync. -->'
$agents = Join-Path $DshHome 'AGENTS.md'
if ((Test-Path $agents) -and -not ((Get-Content $agents -TotalCount 1) -eq $marker)) {
    Move-Item $agents "$agents.backup-$stamp"      # 保住用户自己写的全局指令
    Write-Host "Backed up existing AGENTS.md to $agents.backup-$stamp" -ForegroundColor Yellow
}
$bodies = Get-ChildItem "$repo\rules" -Filter *.mdc | Sort-Object Name | ForEach-Object {
    $text = [IO.File]::ReadAllText($_.FullName) -replace "`r`n", "`n"
    if ($text -match '(?s)\A---\n(.*?)\n---\n(.*)\z') {
        $body = $Matches[2].Trim()
        if ($Matches[1] -match '(?m)^alwaysApply:\s*true\s*$') { $body }
    }
}
$content = (@($marker) + $bodies) -join "`n`n"
[IO.File]::WriteAllText($agents, "$content`n", (New-Object Text.UTF8Encoding $false))
Write-Host "Wrote $agents from $(@($bodies).Count) always-apply rules" -ForegroundColor Green

# --- Skills ---
python "$repo\scripts\install-skills.py" --host dsh --home $DshHome
exit $LASTEXITCODE
