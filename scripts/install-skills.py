"""Link agent-loop's skills and rules and the selected ones of registered packs into one host. Idempotent.

    python scripts/install-skills.py --host cursor|dsh [--home DIR] [--packs FILE] [--uninstall]

A skill pack is a directory with a pack.toml; ~/.agent-loop/packs.txt lists the packs, repository checkouts
and active profiles of this machine. Formats and the rules below are in docs/usage.md#skill-packs.
On dsh, rules are not linked: the always-apply ones are written into $DSH_HOME/AGENTS.md.
Exits 1 when any skill or rule was skipped or any input could not be read.
"""

from __future__ import annotations

import argparse
from collections import Counter
from dataclasses import dataclass, field
from datetime import datetime
import graphlib
import os
from pathlib import Path
import re
import stat
import subprocess
import sys
import tempfile
import tomllib

REPO = Path(__file__).resolve().parents[1]
OWN = "agent-loop"
AGENTS_MARKER = "<!-- Generated by agent-loop scripts/install-skills.py from always-apply rules; edits are overwritten on the next sync. -->"


@dataclass
class Entry:
    name: str
    src: Path
    owner: str
    dest: Path | None
    kind: str = "skill"
    checkout: Path | None = None
    requires: list[str] = field(default_factory=list)
    selected: bool = True
    problem: str = ""
    own: bool = False  # set only when enumerating agent-loop's own skills/ and rules/, never from a pack's chosen name


def norm(path: str | Path) -> str:
    text = str(path)
    if text.startswith("\\\\?\\"):
        text = text[4:]
    # Resolve only the parent: 8.3 names and aliased directories compare equal, and a link is not followed to its target.
    head, tail = os.path.split(os.path.abspath(text))
    return os.path.normcase(os.path.join(os.path.realpath(head), tail))


def link_target(path: Path) -> str | None:
    try:
        return norm(os.readlink(path))
    except (OSError, ValueError):
        return None


def make_link(link: Path, target: Path) -> None:
    if target.is_file():
        os.symlink(target, link)  # Windows: needs Developer Mode or administrator rights
    elif os.name == "nt":
        import _winapi  # junctions need no administrator rights, unlike directory symlinks

        _winapi.CreateJunction(str(target), str(link))
    else:
        os.symlink(target, link, target_is_directory=True)


def remove_link(link: Path) -> None:
    # Junctions and directory symlinks carry the directory attribute even when their target is gone.
    if os.name == "nt" and os.lstat(link).st_file_attributes & stat.FILE_ATTRIBUTE_DIRECTORY:
        os.rmdir(link)
    else:
        os.unlink(link)


def can_link_files(where: Path) -> bool:
    where.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=where) as tmp:
        target = Path(tmp) / "target"
        target.write_text("", encoding="utf-8")
        try:
            make_link(Path(tmp) / "link", target)
        except OSError:
            return False
    return True


def inside(target: str, roots: list[str]) -> bool:
    return any(target == root or target.startswith(root + os.sep) for root in roots)


def read_packs(path: Path, errors: list[str]) -> tuple[list[Path], dict[str, Path], set[str]]:
    packs: list[Path] = []
    repos: dict[str, Path] = {}
    profiles: set[str] = set()
    if not path.exists():
        return packs, repos, profiles
    for number, raw in enumerate(path.read_text(encoding="utf-8-sig").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        key, _, rest = line.partition(" ")
        rest = rest.strip()
        parts = rest.split(None, 1)
        if key == "pack" and rest:
            packs.append(Path(rest))
        elif key == "repo" and len(parts) == 2:
            repos[parts[0]] = Path(parts[1])
        elif key == "profiles":
            profiles = {p.strip() for p in rest.split(",") if p.strip()}
        else:
            errors.append(f"{path}:{number}: cannot read {raw.strip()!r}")
    return packs, repos, profiles


def read_pack(root: Path, repos: dict[str, Path], profiles: set[str], dests: dict[str, Path | None],
              errors: list[str]) -> list[Entry]:
    try:
        data = tomllib.loads((root / "pack.toml").read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        errors.append(f"pack {root}: {exc}")
        return []
    version = data.get("version")
    if version not in (1, 2):
        errors.append(f"pack {root}: unsupported pack.toml version {version!r}")
        return []
    if version == 1 and "rules" in data:
        errors.append(f"pack {root}: [[rules]] needs pack.toml version 2")
        return []
    name = data.get("name") or root.name
    entries = []
    for kind, marker in (("skill", "SKILL.md"), ("rule", None)):
        for entry in data.get(kind + "s", []):
            repo = entry.get("repo")
            if repo and repo not in repos:
                errors.append(f"pack {name}: repo {repo!r} is not registered in packs.txt")
                continue
            base = repos[repo] if repo else root
            src = base / entry.get("path", "")
            if marker and not (src / marker).is_file():
                errors.append(f"pack {name}: no {marker} at {src}")
                continue
            if not marker and not (src.suffix == ".mdc" and src.is_file()):
                errors.append(f"pack {name}: no .mdc rule at {src}")
                continue
            wanted = entry.get("profiles") or []
            entries.append(Entry(src.name, src, name, dests[kind], kind, base if repo else None,
                                 list(entry.get("requires", [])), not wanted or bool(profiles & set(wanted))))
    return entries


def resolve_installable(entries: list[Entry]) -> list[Entry]:
    ok = {s.name: s for s in entries if not s.problem}
    while True:
        dropped = True
        while dropped:
            dropped = False
            for s in list(ok.values()):
                missing = [r for r in s.requires if r not in ok]
                if missing:
                    s.problem = "requires " + ", ".join(missing) + ", which is not installable"
                    del ok[s.name]
                    dropped = True
        try:
            order = graphlib.TopologicalSorter({n: s.requires for n, s in ok.items()}).static_order()
            return [ok[name] for name in order]
        except graphlib.CycleError as exc:
            cycle = exc.args[1]
            for name in set(cycle):
                ok.pop(name).problem = "requires cycle " + " -> ".join(cycle)


def git_state(entry: Entry) -> str:
    def git(*argv: str) -> str | None:
        result = subprocess.run(["git", "-C", str(entry.checkout), *argv], capture_output=True, text=True)
        return result.stdout.strip() if result.returncode == 0 else None

    behind = git("rev-list", "--count", "HEAD..@{u}") or "?"
    dirty = git("status", "--porcelain", "--", str(entry.src))
    return f"   behind={behind} dirty={'?' if dirty is None else 'yes' if dirty else 'no'}"


def always_apply_body(path: Path) -> str | None:
    text = path.read_text(encoding="utf-8-sig").replace("\r\n", "\n")
    match = re.match(r"---\n(.*?)\n---\n(.*)\Z", text, re.S)
    if match and re.search(r"^alwaysApply:\s*true\s*$", match.group(1), re.M):
        return match.group(2).strip()
    return None


def write_agents(home: Path, rules: list[Entry], errors: list[str]) -> None:
    # One writer per home: sync-to-dsh.ps1 and a direct run must not overlap.
    try:
        bodies = [b for b in (always_apply_body(r.src) for r in sorted(rules, key=lambda r: r.name)) if b is not None]
    except OSError as exc:
        errors.append(f"AGENTS.md not written, cannot read a rule: {exc}")
        return
    agents = home / "AGENTS.md"
    try:
        if agents.exists():
            first = agents.read_text(encoding="utf-8-sig").split("\n", 1)[0]
            if not first.startswith("<!-- Generated by agent-loop"):
                backup = agents.with_name(f"AGENTS.md.backup-{datetime.now():%Y%m%d-%H%M%S}")
                backup.write_bytes(agents.read_bytes())
                print(f"Backed up existing AGENTS.md to {backup}")
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", newline="\n", dir=home, delete=False) as tmp:
            tmp.write("\n\n".join([AGENTS_MARKER, *bodies]) + "\n")
        try:
            os.replace(tmp.name, agents)
        except OSError:
            os.unlink(tmp.name)
            raise
    except OSError as exc:
        errors.append(f"AGENTS.md not written: {exc}")
        return
    print(f"Wrote {agents} from {len(bodies)} always-apply rules")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--host", choices=("cursor", "dsh"), required=True)
    parser.add_argument("--home", type=Path, help="host home (default ~/.cursor, or DSH_HOME for dsh)")
    parser.add_argument("--packs", type=Path, default=Path.home() / ".agent-loop" / "packs.txt")
    parser.add_argument("--uninstall", action="store_true", help="remove the links whose target is a registered source")
    args = parser.parse_args(argv)
    if args.host == "cursor":
        home = args.home or Path.home() / ".cursor"
        own_dest, pack_dest, rule_dest = home / "skills-cursor", home / "skills", home / "rules"
    else:
        home = args.home or (Path(os.environ["DSH_HOME"]) if os.environ.get("DSH_HOME") else None)
        if home is None:
            parser.error("dsh home not set: pass --home <path> or set DSH_HOME (dsh defaults to ~/.dsh)")
        own_dest = pack_dest = home / "skills"
        rule_dest = None
    dests = list(dict.fromkeys([own_dest, pack_dest]))

    errors: list[str] = []
    own_rules = REPO / "rules"
    own = [Entry(d.name, d, OWN, own_dest, own=True) for d in sorted((REPO / "skills").iterdir()) if (d / "SKILL.md").is_file()]
    own += [Entry(f.name, f, OWN, rule_dest, "rule", own=True)
            for f in sorted(own_rules.glob("*.mdc")) if f.is_file()] if own_rules.is_dir() else []
    pack_roots, repos, profiles = read_packs(args.packs, errors)
    packed = [s for root in pack_roots
              for s in read_pack(root, repos, profiles, {"skill": pack_dest, "rule": rule_dest}, errors)]
    roots = [norm(REPO / "skills"), norm(own_rules), *(norm(r) for r in pack_roots), *(norm(r) for r in repos.values())]

    # An old install made ~/.cursor/rules one junction into this checkout; links written through it would land in rules/.
    rules_blocked = ""
    if rule_dest is not None and link_target(rule_dest) is not None:
        if link_target(rule_dest) != norm(own_rules):
            rules_blocked = f"{rule_dest} links to {link_target(rule_dest)}"
        elif not args.uninstall and not can_link_files(home):
            rules_blocked = "cannot create file links (Windows needs Developer Mode or administrator rights); kept the old rules junction"
        else:
            remove_link(rule_dest)
            print(f"Removed rules junction: {rule_dest}")
    if rule_dest is not None and not rules_blocked:
        dests.append(rule_dest)

    if args.uninstall:
        for dest in dests:
            for entry in sorted(dest.iterdir()) if dest.is_dir() else []:
                target = link_target(entry)
                if target and inside(target, roots):
                    remove_link(entry)
                    print(f"Removed link: {entry.name}")
        return 0

    for kind in ("skill", "rule"):
        own_names = {s.name for s in own if s.kind == kind}
        chosen = [s for s in packed if s.selected and s.kind == kind]
        counts = Counter(s.name for s in chosen)
        for s in chosen:
            builtin = own_dest / s.name
            if s.name in own_names:
                s.problem = "name also owned by agent-loop"
            elif counts[s.name] > 1:
                s.problem = "name owned by more than one pack: " + ", ".join(sorted(o.owner for o in chosen if o.name == s.name))
            elif kind == "skill" and own_dest != pack_dest and os.path.lexists(builtin) \
                    and not inside(link_target(builtin) or "", roots):
                s.problem = f"{builtin} already exists"
    if rules_blocked:
        for s in own + packed:
            if s.kind == "rule" and s.selected and not s.problem:
                s.problem = rules_blocked
    chosen = [s for s in packed if s.selected]
    install = resolve_installable(own + chosen)
    desired = {norm(s.dest / s.name): norm(s.src) for s in install if s.dest is not None}
    names = {s.name for s in own + chosen}

    for dest in dests:
        dest.mkdir(parents=True, exist_ok=True)
        for entry in sorted(dest.iterdir()):
            target = link_target(entry)
            if target and inside(target, roots) and entry.name not in names:
                try:
                    remove_link(entry)
                except OSError as exc:
                    errors.append(f"cannot remove {entry}: {exc}")
                    continue
                print(f"Removed link: {entry.name}")

    failed = {s.name for s in own + packed if s.problem}
    for s in install:
        if s.dest is None:
            continue
        link = s.dest / s.name
        target = link_target(link)
        current = target == norm(s.src)
        # On Cursor a skill moved between agent-loop and a pack leaves its old link in the other directory.
        stale = [d / s.name for d in dests if d != s.dest and inside(link_target(d / s.name) or "", roots)]
        blocked = [r for r in s.requires if r in failed]
        if blocked:
            s.problem = "requires " + ", ".join(blocked) + ", which was not linked"
        elif current and not stale:
            continue
        elif target is not None and not s.own and not inside(target, roots):
            s.problem = f"{link} links to {target}, outside the registered sources"
        elif target is None and os.path.lexists(link):
            s.problem = f"{link} is a plain {'directory' if s.kind == 'skill' else 'file'}"
        else:
            try:
                for old in stale:
                    remove_link(old)
                    print(f"Removed link: {old.name}")
                if not current:
                    if target is not None:
                        remove_link(link)  # an old registered source, or an agent-loop entry left behind by a moved checkout
                    make_link(link, s.src)
            except OSError as exc:
                s.problem = f"cannot link {link}: {exc}"
        if s.problem:
            failed.add(s.name)
        elif not current:
            print(f"Linked {s.kind}: {s.name}")

    if rule_dest is None and errors:
        errors.append("AGENTS.md not written because of the errors above")
    elif rule_dest is None:
        write_agents(home, [s for s in install if s.kind == "rule" and not s.problem], errors)

    width = max(len(owner) for owner in ["unmanaged", OWN, *(s.owner for s in packed)])
    for kind, title in (("skill", "Skills"), ("rule", "Rules")):
        print(f"\n--- {title} ({args.host}) ---")
        for s in own + packed:
            if s.kind != kind:
                continue
            if s.problem:
                status = f"SKIPPED: {s.problem}"
            elif not s.selected:
                status = "not selected by profiles"
            else:
                status = f"-> {s.src}" + (git_state(s) if s.checkout else "")
            print(f"{s.name:<26} {s.owner:<{width}} {status}")
    for dest in dests:
        for entry in sorted(dest.iterdir()):
            target = link_target(entry)
            if target and norm(entry) not in desired:
                print(f"{entry.name:<26} {'unmanaged':<{width}} -> {target}")
    problems = errors + [f"{s.name}: {s.problem}" for s in own + packed if s.problem]
    for problem in problems:
        print(f"ERROR: {problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
